package ru.moysklad.intern.patterns.model;

/**
 * Тип покупателя (контрагента) в заказе покупателя.
 */
public enum CustomerType {

    /** Обычный покупатель: скидка 0%. */
    REGULAR,

    /** Оптовый покупатель: скидка 10% при сумме товаров от 50 000 ₽. */
    WHOLESALE,

    /** VIP-покупатель: скидка 15% независимо от суммы. */
    VIP,

    /**
     * Корпоративный покупатель. Тип уже заведён в справочнике контрагентов,
     * но условия скидки для него ещё не утверждены: стратегии нет,
     * и фабрика обязана сообщить, что тип не поддерживается.
     */
    CORPORATE
}
