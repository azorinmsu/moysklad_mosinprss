package ru.moysklad.intern.documentpatterns.model;

/**
 * Бизнес-коды ошибок обработки документов. Тесты проверяют именно код, а не текст сообщения.
 */
public enum DocumentErrorCode {
    /** Документ не передан. */
    DOCUMENT_REQUIRED,
    /** В документе нет ни одной позиции. */
    EMPTY_DOCUMENT,
    /** Количество в позиции не положительное. */
    INVALID_QUANTITY,
    /** Не указан склад-источник, хотя тип документа его требует. */
    MISSING_SOURCE_WAREHOUSE,
    /** Не указан склад-получатель, хотя тип документа его требует. */
    MISSING_TARGET_WAREHOUSE,
    /** Склад-источник и склад-получатель совпадают. */
    SAME_WAREHOUSES,
    /** Указан склад-источник, который этому типу документа не нужен (например, у приёмки). */
    UNEXPECTED_SOURCE_WAREHOUSE,
    /** Указан склад-получатель, который этому типу документа не нужен (например, у отгрузки). */
    UNEXPECTED_TARGET_WAREHOUSE,
    /** Одна и та же пара «товар + партия» встречается в документе несколько раз. */
    DUPLICATE_POSITION,
    /** Недостаточно товара на складе. */
    INSUFFICIENT_STOCK,
    /** Документ уже проведён. */
    ALREADY_POSTED,
    /** Документ не проведён, отменять нечего. */
    NOT_POSTED,
    /** Проведение документа уже отменено. */
    ALREADY_CANCELLED,
    /** Документ не в статусе DRAFT — менять реквизиты и позиции нельзя. */
    DOCUMENT_NOT_EDITABLE,
    /** Для типа документа не зарегистрирована фабрика. */
    UNSUPPORTED_DOCUMENT_TYPE
}
